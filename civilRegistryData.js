// ─── Helpers ──────────────────────────────────────────────────────────────────
function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }

function pickDialogue(type) {
  const pool = DIALOGUES[type] || DIALOGUES.normal;
  return pick(pool);
}

function pickWanted() { return pick(WANTED_LIST); }
function pickGov()    { return pick(GOVERNORATES); }

function pickFullName(gender) {
  const first = gender === "M" ? pick(FIRST_NAMES_M) : pick(FIRST_NAMES_F);
  const mid   = pick(MID_LAST_NAMES);
  const last  = pick(MID_LAST_NAMES);
  return `${first} ${mid} ${last}`;
}

function pickRequestType(gender) {
  const rt = pick(REQUEST_TYPES);
  const requiredDocs = rt.docs.filter(d => gender === "M" || !rt.docsMaleOnly.includes(d));
  return { ...rt, requiredDocs };
}

/** اسم زوجة ثابت بناءً على الرقم القومي */
function generateWifeName(nationalId) {
  const femaleFirstNames = ["فاطمة","مريم","نور","سارة","هبة","رنا","دينا","ريم","منى","لمياء","آية","رانيا","سمر","نهى","ولاء"];
  const lastNames = ["محمد","أحمد","علي","حسن","إبراهيم","سالم","عوض","رزق","فتحي","شعبان"];
  const seed = parseInt(nationalId.slice(-4));
  const first = femaleFirstNames[seed % femaleFirstNames.length];
  const last  = lastNames[Math.floor(seed / femaleFirstNames.length) % lastNames.length];
  return `${first} ${last}`;
}

function pickGameEvent()              { return pick(GAME_EVENTS); }
function pickManagerWarning(level)    { return pick(MANAGER_WARNINGS[level] || MANAGER_WARNINGS.warning); }
function formatForgeReason(reason)    { return FORGE_REASONS_TEXT[reason] || reason; }

function getReportMessage(accuracy) {
  if (accuracy >= 0.9) return pick(REPORT_MESSAGES.excellent);
  if (accuracy >= 0.7) return pick(REPORT_MESSAGES.good);
  if (accuracy >= 0.5) return pick(REPORT_MESSAGES.average);
  return pick(REPORT_MESSAGES.bad);
}

